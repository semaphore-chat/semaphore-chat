//! Generates `semaphore-wire` and `semaphore-api` from the pinned contract.
//!
//!     gen-api <contract-dir> <wire-out> <api-out> <events-out>
//!
//! Run it with `native/scripts/gen-api.sh`, which does it in the build image.

mod enums;
mod events;
mod spec;

use std::path::{Path, PathBuf};

use anyhow::Context;
use quote::quote;
use syn::punctuated::Punctuated;
use syn::{Token, parse_quote};

/// Schemas not generated: `semaphore-wire/src/overrides.rs` defines them.
const OVERRIDDEN: &[&str] = &["UpdateMessageDto"];

const HEADER: &str = "// @generated by tools/gen-api from native/contract. Do not edit.\n";

fn main() -> anyhow::Result<()> {
    let arguments: Vec<String> = std::env::args().skip(1).collect();
    let [contract, wire_out, api_out, events_out] = arguments.as_slice() else {
        anyhow::bail!("usage: gen-api <contract-dir> <wire-out> <api-out> <events-out>");
    };
    let contract = PathBuf::from(contract);
    let wire_out = PathBuf::from(wire_out);
    let api_out = PathBuf::from(api_out);
    let events_out = PathBuf::from(events_out);

    let openapi = spec::load(&contract.join("openapi.json"))?;
    let named_enums = spec::enums(&openapi)?;

    let document: openapiv3::OpenAPI =
        serde_json::from_value(openapi).context("converting openapi.json")?;

    // Point every named enum at the tolerant type the generated `enums` module defines, so
    // progenitor never generates a closed one.
    let mut settings = progenitor::GenerationSettings::new();
    for enum_def in &named_enums {
        settings.with_replacement(
            &enum_def.name,
            format!("semaphore_wire::enums::{}", enum_def.name),
            std::iter::empty::<progenitor::TypeImpl>(),
        );
    }

    // Types written by hand in `semaphore-wire/src/overrides.rs`, where the generated shape loses
    // something the server reads. Each one says why there.
    for name in OVERRIDDEN {
        settings.with_replacement(
            name,
            format!("semaphore_wire::overrides::{name}"),
            std::iter::empty::<progenitor::TypeImpl>(),
        );
    }

    let mut generator = progenitor::Generator::new(&settings);
    let tokens = generator
        .generate_tokens(&document)
        .context("generating from openapi.json")?;
    let generated: syn::File = syn::parse2(tokens).context("parsing progenitor's output")?;

    let (types, client) = split(generated);
    let types = tolerate_missing_optionals(types)?;

    let wire = format!(
        "{HEADER}#![allow(clippy::all)]\n\n{}\n{}",
        enums::module_source(&named_enums),
        prettyplease::unparse(&file(vec![types]))
    );
    write(&wire_out, &wire)?;

    let mut client = client;
    client.insert(
        0,
        parse_quote!(
            use semaphore_wire as types;
        ),
    );
    let api = format!(
        "{HEADER}#![allow(clippy::all)]\n#![allow(dead_code, unused_imports)]\n\n{}",
        prettyplease::unparse(&file(client))
    );
    write(&api_out, &api)?;

    let socket_events = std::fs::read_to_string(contract.join("socket-events.json"))
        .context("reading socket-events.json")?;
    let socket_events: serde_json::Value =
        serde_json::from_str(&socket_events).context("parsing socket-events.json")?;
    let events = format!(
        "{HEADER}{}",
        events::module_source(&socket_events).context("generating the event module")?
    );
    write(&events_out, &events)?;

    Ok(())
}

/// Splits progenitor's output into the `types` module and everything else.
fn split(mut generated: syn::File) -> (syn::Item, Vec<syn::Item>) {
    let types = generated
        .items
        .iter()
        .position(|item| matches!(item, syn::Item::Mod(module) if module.ident == "types"))
        .expect("progenitor always emits a types module");
    let types = generated.items.remove(types);
    (types, generated.items)
}

/// Gives every `Option` field `#[serde(default)]`.
///
/// A required nullable field is always present on a server that matches the schema, but a
/// missing one means the same as `null` (wire-contract rule 4), and serde would otherwise
/// reject the whole payload. Only the `Option` fields are touched.
fn tolerate_missing_optionals(mut types: syn::Item) -> anyhow::Result<syn::Item> {
    let syn::Item::Mod(module) = &mut types else {
        anyhow::bail!("the types item is not a module");
    };
    let Some((_, items)) = &mut module.content else {
        anyhow::bail!("the types module has no body");
    };
    for item in items.iter_mut() {
        let syn::Item::Struct(item) = item else {
            continue;
        };
        for field in &mut item.fields {
            if is_option(&field.ty) {
                ensure_serde_default(&mut field.attrs)?;
            }
        }
    }
    Ok(types)
}

fn is_option(ty: &syn::Type) -> bool {
    let syn::Type::Path(path) = ty else {
        return false;
    };
    path.path
        .segments
        .last()
        .is_some_and(|segment| segment.ident == "Option")
}

fn ensure_serde_default(attrs: &mut Vec<syn::Attribute>) -> anyhow::Result<()> {
    let Some(index) = attrs.iter().position(|attr| attr.path().is_ident("serde")) else {
        attrs.push(parse_quote!(#[serde(default)]));
        return Ok(());
    };
    let syn::Meta::List(list) = &mut attrs[index].meta else {
        anyhow::bail!("a serde attribute that is not a list");
    };
    let mut entries = list.parse_args_with(Punctuated::<syn::Meta, Token![,]>::parse_terminated)?;
    if entries.iter().any(|entry| entry.path().is_ident("default")) {
        return Ok(());
    }
    entries.push(parse_quote!(default));
    list.tokens = quote!(#entries);
    Ok(())
}

fn file(items: Vec<syn::Item>) -> syn::File {
    syn::File {
        shebang: None,
        attrs: Vec::new(),
        items,
    }
}

fn write(path: &Path, text: &str) -> anyhow::Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("creating {}", parent.display()))?;
    }
    std::fs::write(path, text).with_context(|| format!("writing {}", path.display()))?;
    let status = std::process::Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(path)
        .status()
        .context("running rustfmt")?;
    anyhow::ensure!(status.success(), "rustfmt failed on {}", path.display());
    let lines = std::fs::read_to_string(path)?.lines().count();
    println!("wrote {} ({lines} lines)", path.display());
    Ok(())
}
