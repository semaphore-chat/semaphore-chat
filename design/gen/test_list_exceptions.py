"""Tests for `design/gen/list_exceptions.py`, run with the Python standard library only.

    python3 -m unittest discover -s design/gen -p 'test_*.py' -v
"""

from __future__ import annotations

import contextlib
import io
import pathlib
import sys
import tempfile
import unittest

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import list_exceptions as lx  # noqa: E402  (after the path fix above)

PAGE = pathlib.Path("design") / "guide" / "exceptions.md"


class TempRepo(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = pathlib.Path(self._tmp.name)

    def put(self, rel: str, text: str) -> None:
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    def page(self) -> str:
        return (self.root / PAGE).read_text(encoding="utf-8")

    def run_cli(self, check: bool) -> tuple[int, str]:
        err = io.StringIO()
        with contextlib.redirect_stdout(err):
            code = lx.run(self.root, check=check)
        return code, err.getvalue()


class FindTests(TempRepo):
    def test_finds_exception_in_tsx_and_rs_with_line_numbers(self) -> None:
        self.put(
            "frontend/src/screens/A.tsx",
            "const a = 1;\n\nconst b = 2; // design-exception: old grid\n",
        )
        self.put(
            "native/crates/semaphore-ui/src/x.rs",
            "fn f() {}\n// design-exception: custom gauge\nfn g() {}\n",
        )
        self.assertEqual(
            lx.find_exceptions(self.root),
            [
                ("frontend/src/screens/A.tsx", 3, "old grid"),
                ("native/crates/semaphore-ui/src/x.rs", 2, "custom gauge"),
            ],
        )

    def test_finds_css_and_block_comments(self) -> None:
        self.put("frontend/src/a.css", "a { /* design-exception: legacy colour */ }\n")
        self.put("frontend/src/b.tsx", "<div>{/* design-exception: one-off */}</div>\n")
        found = {(p, r) for p, _, r in lx.find_exceptions(self.root)}
        self.assertEqual(
            found,
            {("frontend/src/a.css", "legacy colour"), ("frontend/src/b.tsx", "one-off")},
        )

    def test_ignores_skipped_folders(self) -> None:
        text = "// design-exception: no\n"
        self.put("frontend/src/api-client/a.ts", text)
        self.put("frontend/src/__tests__/a.test.tsx", text)
        self.put("native/crates/c/target/debug/a.rs", text)
        self.put("native/crates/c/src/b.rs", text)
        self.assertEqual(
            [p for p, _, _ in lx.find_exceptions(self.root)],
            ["native/crates/c/src/b.rs"],
        )

    def test_ignores_generated_files_and_other_suffixes(self) -> None:
        self.put("frontend/src/g.ts", "// @generated by x\n// design-exception: no\n")
        self.put("native/crates/c/g.rs", "// @generated\n// design-exception: no\n")
        self.put("frontend/src/readme.md", "// design-exception: no\n")
        self.assertEqual(lx.find_exceptions(self.root), [])

    def test_marker_outside_a_comment_is_ignored(self) -> None:
        self.put("frontend/src/a.ts", "const s = 'design-exception: not a comment';\n")
        self.assertEqual(lx.find_exceptions(self.root), [])

    def test_sorted_by_path_then_line(self) -> None:
        self.put("frontend/src/b.ts", "// design-exception: b1\n\n// design-exception: b2\n")
        self.put("frontend/src/a.ts", "\n\n// design-exception: a3\n")
        self.assertEqual(
            [(p, n) for p, n, _ in lx.find_exceptions(self.root)],
            [("frontend/src/a.ts", 3), ("frontend/src/b.ts", 1), ("frontend/src/b.ts", 3)],
        )


class PageTests(TempRepo):
    def test_empty_tree_says_no_exceptions(self) -> None:
        self.assertEqual(self.run_cli(check=False)[0], 0)
        text = self.page()
        self.assertIn("There are no exceptions.", text)
        self.assertNotIn("|Where|", text)
        self.assertTrue(text.endswith("\n") and not text.endswith("\n\n"))

    def test_table_for_exceptions(self) -> None:
        self.put("frontend/src/a.ts", "// design-exception: because\n")
        self.run_cli(check=False)
        text = self.page()
        self.assertIn("|Where|Reason|", text)
        self.assertIn("|`frontend/src/a.ts:1`|because|", text)
        self.assertNotIn("There are no exceptions.", text)

    def test_pipe_in_reason_does_not_break_the_table(self) -> None:
        self.put("frontend/src/a.ts", "// design-exception: a | b\n")
        self.run_cli(check=False)
        row = [x for x in self.page().splitlines() if "a.ts:1" in x][0]
        self.assertEqual(row, "|`frontend/src/a.ts:1`|a \\| b|")

    def test_output_is_deterministic(self) -> None:
        self.put("frontend/src/a.ts", "// design-exception: x\n")
        self.run_cli(check=False)
        first = self.page()
        self.run_cli(check=False)
        self.assertEqual(first, self.page())


class CheckTests(TempRepo):
    def test_check_passes_after_write(self) -> None:
        self.put("frontend/src/a.ts", "// design-exception: x\n")
        self.run_cli(check=False)
        self.assertEqual(self.run_cli(check=True), (0, ""))

    def test_check_fails_when_missing(self) -> None:
        code, out = self.run_cli(check=True)
        self.assertEqual(code, 1)
        self.assertEqual(out, "stale: design/guide/exceptions.md\n")
        self.assertFalse((self.root / PAGE).exists())

    def test_check_fails_after_edit_and_writes_nothing(self) -> None:
        self.run_cli(check=False)
        (self.root / PAGE).write_text("edited\n", encoding="utf-8")
        self.assertEqual(self.run_cli(check=True)[0], 1)
        self.assertEqual(self.page(), "edited\n")

    def test_check_fails_when_code_changes(self) -> None:
        self.run_cli(check=False)
        self.put("frontend/src/a.ts", "// design-exception: new\n")
        self.assertEqual(self.run_cli(check=True)[0], 1)


if __name__ == "__main__":
    unittest.main()
