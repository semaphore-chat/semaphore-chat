"""Load the behaviour patterns in `design/behaviour/` and render their vectors.

A pattern file is the human statement of one interaction pattern: its
parameters, state, events, effects and rules, and its scenarios (a name and a
list of events). `behaviour_ref.py` is the executable definition. This module
validates every pattern file, runs each scenario through the reference, and
renders the resulting vectors for the shared JSON, the web client and the
Rust client. `gen_tokens.py` calls it, as it does `gen_icons.py`.

Errors are `TokenError`s whose message starts with `behaviour.<pattern>`.
Only the Python standard library is used.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from gen_error import TokenError

PATTERN_DIR = Path("design") / "behaviour"
VECTORS_OUTPUT = Path("design") / "vectors" / "behaviour.json"
TS_OUTPUT = Path("frontend/src/kit/behaviour/generated/vectors.ts")
RS_OUTPUT = Path("native/crates/semaphore-design/src/behaviour_vectors.rs")

FIELDS = ("pattern", "doc", "params", "state", "events", "effects", "rules", "scenarios")
SCENARIO_FIELDS = ("name", "covers", "events")
SCENARIO_OPTIONAL = ("params", "initial")
NAME = re.compile(r"[a-z][A-Za-z0-9]*")
TOKEN_REF = re.compile(r"motion\.([a-z0-9][A-Za-z0-9]*)")
# The most a whole number may be in behaviour data: both ports hold it exactly.
INT_MAX = 2**53 - 1

HEADER = (
    "// @generated by design/gen/gen_tokens.py from design/behaviour/*.json.\n"
    "// Do not edit by hand: change the source or the generator and re-run it."
)


def _fail(path: str, message: str) -> None:
    raise TokenError(f"{path}: {message}")


def kebab(name: str) -> str:
    """`toastQueue` -> `toast-queue`, the pattern's file name."""
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def canonical(value: object) -> str:
    """The canonical JSON form shared by the three outputs and both ports.

    Object keys sorted by code point, no whitespace, whole numbers in plain
    decimal, strings with only `"` and `\\` escaped (control characters are
    rejected before this point), `null`, `true`, `false`.
    """
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def _value(path: str, value: object) -> None:
    """Behaviour data: objects, lists, strings without control characters, whole numbers,
    booleans and null. No fractions, so every value has one canonical form."""
    if value is None or isinstance(value, bool):
        return
    if isinstance(value, int):
        if abs(value) > INT_MAX:
            _fail(path, f"expected a whole number of at most {INT_MAX}, got {value!r}")
        return
    if isinstance(value, float):
        _fail(path, f"expected a whole number, got {value!r} (behaviour data has no fractions)")
    if isinstance(value, str):
        if any(ord(ch) < 0x20 for ch in value):
            _fail(path, f"expected a string without control characters, got {value!r}")
        return
    if isinstance(value, list):
        for index, item in enumerate(value):
            _value(f"{path}[{index}]", item)
        return
    if isinstance(value, dict):
        for key, item in value.items():
            if not isinstance(key, str) or not NAME.fullmatch(key):
                _fail(f"{path}.{key}", "expected a camelCase name")
            _value(f"{path}.{key}", item)
        return
    _fail(path, f"unexpected value {value!r}")


def _mapping(path: str, value: object) -> dict:
    if not isinstance(value, dict):
        _fail(path, f"expected an object, got {value!r}")
    return value


def _names(path: str, value: object) -> dict:
    """An object whose keys are camelCase names."""
    value = _mapping(path, value)
    for key in value:
        if not NAME.fullmatch(key):
            _fail(f"{path}.{key}", "expected a camelCase name")
    return value


def _text(path: str, value: object) -> str:
    if not isinstance(value, str) or not value.strip():
        _fail(path, f"expected a non-empty sentence, got {value!r}")
    return value


def _param(path: str, value: object, motion: dict) -> object:
    """A parameter value, with a `motion.<name>` reference resolved to its milliseconds."""
    if isinstance(value, str):
        match = TOKEN_REF.fullmatch(value)
        if not match:
            _fail(path, f"expected a number, a boolean or motion.<name>, got {value!r}")
        if match.group(1) not in motion:
            _fail(path, f"unknown token {value!r}")
        return int(motion[match.group(1)])
    if isinstance(value, bool):
        return value
    if isinstance(value, float) or not isinstance(value, int) or value < 0:
        _fail(path, f"expected a whole number from 0, a boolean or motion.<name>, got {value!r}")
    _value(path, value)
    return value


def _declared(path: str, value: object) -> dict:
    """`events` or `effects`: name -> {field: type description}."""
    value = _names(path, value)
    if not value:
        _fail(path, "expected at least one entry")
    for name, fields in value.items():
        for field, description in _names(f"{path}.{name}", fields).items():
            _text(f"{path}.{name}.{field}", description)
    return value


def _event(path: str, event: object, events: dict) -> None:
    """A scenario event: one declared name with exactly its declared fields."""
    if not isinstance(event, dict) or len(event) != 1:
        _fail(path, f"expected an object with one key, the event name, got {event!r}")
    ((name, fields),) = event.items()
    if name not in events:
        _fail(f"{path}.{name}", "unknown event")
    fields = _mapping(f"{path}.{name}", fields)
    for field in fields:
        if field not in events[name]:
            _fail(f"{path}.{name}.{field}", "unknown field")
    for field in events[name]:
        if field not in fields:
            _fail(f"{path}.{name}.{field}", "missing")
    _value(f"{path}.{name}", fields)


def validate_pattern(data: object, file_stem: str, motion: dict) -> dict:
    """Check one parsed pattern file; return it with `resolved` params added."""
    data = _mapping(f"behaviour.{file_stem}", data)
    name = data.get("pattern")
    if not isinstance(name, str) or not NAME.fullmatch(name):
        _fail(f"behaviour.{file_stem}.pattern", f"expected a camelCase name, got {name!r}")
    base = f"behaviour.{name}"
    if kebab(name) != file_stem:
        _fail(f"{base}.pattern", f"expected the file to be named {kebab(name)}.json, got {file_stem}.json")
    for key in data:
        if key not in FIELDS:
            _fail(f"{base}.{key}", "unknown entry")
    for key in FIELDS:
        if key not in data:
            _fail(f"{base}.{key}", "missing")
    _text(f"{base}.doc", data["doc"])
    params = _names(f"{base}.params", data["params"])
    resolved = {key: _param(f"{base}.params.{key}", value, motion) for key, value in params.items()}
    state = _names(f"{base}.state", data["state"])
    if not state:
        _fail(f"{base}.state", "expected at least one field")
    for field, description in state.items():
        _text(f"{base}.state.{field}", description)
    events = _declared(f"{base}.events", data["events"])
    _declared(f"{base}.effects", data["effects"])

    rules = data["rules"]
    if not isinstance(rules, list) or not rules:
        _fail(f"{base}.rules", "expected a list of sentences")
    for index, rule in enumerate(rules):
        _text(f"{base}.rules[{index}]", rule)
        if rules.index(rule) != index:
            _fail(f"{base}.rules[{index}]", "duplicate rule")

    scenarios = data["scenarios"]
    if not isinstance(scenarios, list) or not scenarios:
        _fail(f"{base}.scenarios", "expected a list of scenarios")
    seen: set[str] = set()
    scenario_params: list[dict] = []
    covered: set[int] = set()
    for index, scenario in enumerate(scenarios):
        path = f"{base}.scenarios[{index}]"
        scenario = _mapping(path, scenario)
        for key in scenario:
            if key not in SCENARIO_FIELDS + SCENARIO_OPTIONAL:
                _fail(f"{path}.{key}", "unknown entry")
        for key in SCENARIO_FIELDS:
            if key not in scenario:
                _fail(f"{path}.{key}", "missing")
        title = _text(f"{path}.name", scenario["name"])
        if title in seen:
            _fail(f"{path}.name", f"duplicate scenario name {title!r}")
        seen.add(title)
        covers = scenario["covers"]
        if not isinstance(covers, list) or not covers:
            _fail(f"{path}.covers", "expected a list of rule numbers")
        for number in covers:
            if isinstance(number, bool) or not isinstance(number, int) or not 1 <= number <= len(rules):
                _fail(f"{path}.covers", f"expected rule numbers from 1 to {len(rules)}, got {number!r}")
            covered.add(number)
        overrides = {}
        for key, value in _names(f"{path}.params", scenario.get("params", {})).items():
            if key not in params:
                _fail(f"{path}.params.{key}", "unknown parameter")
            overrides[key] = _param(f"{path}.params.{key}", value, motion)
        scenario_params.append({**resolved, **overrides})
        initial = _names(f"{path}.initial", scenario.get("initial", {}))
        for key, value in initial.items():
            if key not in state:
                _fail(f"{path}.initial.{key}", "unknown state field")
            _value(f"{path}.initial.{key}", value)
        steps = scenario["events"]
        if not isinstance(steps, list) or not steps:
            _fail(f"{path}.events", "expected a list of events")
        for number, event in enumerate(steps):
            _event(f"{path}.events[{number}]", event, events)
    missing = [str(number) for number in range(1, len(rules) + 1) if number not in covered]
    if missing:
        _fail(f"{base}.rules", f"no scenario covers rule {', '.join(missing)}")
    return {**data, "resolved": resolved, "scenarioParams": scenario_params}


def load_patterns(root: Path, tokens: dict) -> list[dict]:
    """Every pattern file below `root`, validated, in file name order."""
    # Imported here so a broken token source reaches `main` first, and so the
    # JSON reader with its duplicate-key check is the generator's own.
    import gen_tokens

    directory = Path(root) / PATTERN_DIR
    files = sorted(directory.glob("*.json"))
    if not files:
        _fail("behaviour", f"no pattern files in {PATTERN_DIR.as_posix()}")
    # The file name follows the pattern name, so two files cannot share a pattern.
    patterns = []
    for file in files:
        try:
            data = gen_tokens._read_json(file)
        except TokenError as error:
            raise TokenError(f"behaviour.{file.stem}: {error}") from error
        patterns.append(validate_pattern(data, file.stem, tokens["motion"]))
    return patterns


def _check_record(path: str, record: dict, pattern: dict) -> None:
    """The reference's output must match what the pattern file declares."""
    state = record["state"]
    if set(state) != set(pattern["state"]):
        _fail(f"{path}.state", f"the reference returned fields {sorted(state)}, the file declares {sorted(pattern['state'])}")
    _value(f"{path}.state", state)
    for effect in record["effects"]:
        ((name, fields),) = effect.items()
        declared = pattern["effects"].get(name)
        if declared is None:
            _fail(f"{path}.effects.{name}", "the reference emitted an undeclared effect")
        if set(fields) != set(declared):
            _fail(f"{path}.effects.{name}", f"the reference emitted fields {sorted(fields)}, the file declares {sorted(declared)}")
        _value(f"{path}.effects.{name}", fields)


def sort_keys(value: object) -> object:
    """A copy of `value` with every object's keys in code point order, as the canonical form has them."""
    if isinstance(value, dict):
        return {key: sort_keys(value[key]) for key in sorted(value)}
    if isinstance(value, list):
        return [sort_keys(item) for item in value]
    return value


def build(patterns: list[dict]) -> dict:
    """Pattern name -> {params, initial, vectors}: what every output renders."""
    import behaviour_ref

    built = {}
    for pattern in patterns:
        name = pattern["pattern"]
        base = f"behaviour.{name}"
        if name not in behaviour_ref.PATTERNS:
            _fail(base, "no reference reducer in design/gen/behaviour_ref.py")
        handled = behaviour_ref.PATTERNS[name][2]
        if set(handled) != set(pattern["events"]):
            _fail(f"{base}.events", f"the file declares {sorted(pattern['events'])}, the reference handles {sorted(handled)}")
        defaults = pattern["resolved"]
        initial = behaviour_ref.initial_state(name, defaults)
        vectors = []
        for index, scenario in enumerate(pattern["scenarios"]):
            params = pattern["scenarioParams"][index]
            start = behaviour_ref.initial_state(name, params, scenario.get("initial"))
            try:
                records = behaviour_ref.run_scenario(
                    name, {"params": params, "initial": scenario.get("initial"), "events": scenario["events"]}
                )
            except behaviour_ref.BehaviourError as error:
                raise TokenError(f"{base}.scenarios[{index}]: {error}") from error
            for number, record in enumerate(records):
                _check_record(f"{base}.scenarios[{index}].events[{number}]", record, pattern)
            steps = [
                {key: sort_keys(record[key]) for key in ("event", "state", "effects")}
                for record in records
            ]
            vectors.append(
                {
                    "name": scenario["name"],
                    "params": sort_keys(params),
                    "initial": sort_keys(start),
                    "steps": steps,
                }
            )
        built[name] = {
            "params": sort_keys(defaults),
            "initial": sort_keys(initial),
            "vectors": vectors,
        }
    return built


def render_json(built: dict) -> str:
    """The shared vectors: two-space indent. The structure keeps a fixed order (name,
    params, initial, steps; event, state, effects); the data inside has sorted keys."""
    return json.dumps(built, indent=2, ensure_ascii=False) + "\n"


TS_IDENTIFIER = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")


def _ts_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _ts_value(value: object, indent: int) -> list[str]:
    """A value as TypeScript lines; the first line carries no indent of its own."""
    pad = "  " * (indent + 1)
    close = "  " * indent
    if value is None:
        return ["null"]
    if isinstance(value, bool):
        return ["true" if value else "false"]
    if isinstance(value, int):
        return [str(value)]
    if isinstance(value, str):
        return [_ts_string(value)]
    if isinstance(value, list):
        if not value:
            return ["[]"]
        lines = ["["]
        for item in value:
            inner = _ts_value(item, indent + 1)
            lines.append(pad + inner[0])
            lines.extend(inner[1:])
            lines[-1] += ","
        lines.append(close + "]")
        return lines
    if not value:
        return ["{}"]
    lines = ["{"]
    for key in value:
        label = key if TS_IDENTIFIER.fullmatch(key) else _ts_string(key)
        inner = _ts_value(value[key], indent + 1)
        lines.append(f"{pad}{label}: {inner[0]}")
        lines.extend(inner[1:])
        lines[-1] += ","
    lines.append(close + "}")
    return lines


def render_ts(built: dict) -> str:
    """The same data for the web client, as one `as const` object."""
    body = _ts_value(built, 0)
    lines = [
        HEADER,
        "",
        "// Pattern name -> its default params, its initial state and its vectors. Each vector",
        "// step is an event, then the full state and the exact ordered effects after it.",
        "// Compare with deep equality. See design/README.md, \"Behaviour\".",
        "",
        "export const behaviourVectors = " + body[0],
        *body[1:-1],
        body[-1] + " as const;",
        "",
        "export type BehaviourPattern = keyof typeof behaviourVectors;",
    ]
    return "\n".join(lines) + "\n"


def _rs_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


RS_PRELUDE = """\
//! The shared behaviour vectors, generated from `design/behaviour/*.json`.
//!
//! Test-only data for the hand-written reducers, with no JSON dependency: every params object,
//! state, event and effect list is a string in the canonical JSON form, which a port's tests
//! compare with their own serialisation of the same value. The canonical form: object keys sorted
//! by code point; no whitespace; whole numbers only, in plain decimal (`-` for a negative, no
//! leading zeros, no exponent); strings in double quotes with only `"` and `\\` escaped, as `\\"`
//! and `\\\\` (behaviour data has no control characters), other characters as UTF-8; `null`,
//! `true` and `false`. See `design/README.md`, "Behaviour".

/// One step of a vector: the event, then the full state and the ordered effects after it.
pub(crate) struct Step {
    pub event: &'static str,
    pub state: &'static str,
    pub effects: &'static str,
}

/// One named scenario: its params in full, the state it starts from and its steps.
pub(crate) struct Vector {
    pub name: &'static str,
    pub params: &'static str,
    pub initial: &'static str,
    pub steps: &'static [Step],
}

/// One pattern: its default params, its initial state for them and its vectors.
pub(crate) struct Pattern {
    pub name: &'static str,
    pub params: &'static str,
    pub initial: &'static str,
    pub vectors: &'static [Vector],
}
"""

RS_TESTS = """\

/// The data is whole: every pattern has vectors, and every string is canonical in shape.
#[test]
fn behaviour_vectors_are_complete() {
    let mut names: Vec<&str> = PATTERNS.iter().map(|pattern| pattern.name).collect();
    names.dedup();
    assert_eq!(names.len(), PATTERNS.len());
    for pattern in PATTERNS {
        assert!(pattern.params.starts_with('{'), "{}", pattern.name);
        assert!(pattern.initial.starts_with('{'), "{}", pattern.name);
        assert!(!pattern.vectors.is_empty(), "{}", pattern.name);
        for vector in pattern.vectors {
            assert!(!vector.name.is_empty());
            assert!(vector.params.starts_with('{'), "{}", vector.name);
            assert!(vector.initial.starts_with('{'), "{}", vector.name);
            assert!(!vector.steps.is_empty(), "{}", vector.name);
            for step in vector.steps {
                assert!(step.event.starts_with('{'), "{}", vector.name);
                assert!(step.state.starts_with('{'), "{}", vector.name);
                assert!(step.effects.starts_with('['), "{}", vector.name);
                for text in [step.event, step.state, step.effects] {
                    assert!(!text.contains('\\n') && !text.contains(": "), "{text}");
                }
            }
        }
    }
}
"""


def render_rs(built: dict) -> str:
    """The same data for the Rust client: canonical JSON strings, test-only."""
    lines = [HEADER, "", RS_PRELUDE.rstrip("\n"), "", "/// Every pattern, in pattern name order.",
             "#[rustfmt::skip]", "pub(crate) const PATTERNS: &[Pattern] = &["]
    for name in sorted(built):
        pattern = built[name]
        lines += [
            "    Pattern {",
            f"        name: {_rs_string(name)},",
            f"        params: {_rs_string(canonical(pattern['params']))},",
            f"        initial: {_rs_string(canonical(pattern['initial']))},",
            "        vectors: &[",
        ]
        for vector in pattern["vectors"]:
            lines += [
                "            Vector {",
                f"                name: {_rs_string(vector['name'])},",
                f"                params: {_rs_string(canonical(vector['params']))},",
                f"                initial: {_rs_string(canonical(vector['initial']))},",
                "                steps: &[",
            ]
            for step in vector["steps"]:
                lines += [
                    "                    Step {",
                    f"                        event: {_rs_string(canonical(step['event']))},",
                    f"                        state: {_rs_string(canonical(step['state']))},",
                    f"                        effects: {_rs_string(canonical(step['effects']))},",
                    "                    },",
                ]
            lines += ["                ],", "            },"]
        lines += ["        ],", "    },"]
    lines.append("];")
    return "\n".join(lines) + "\n" + RS_TESTS


def renderers(patterns: list[dict]) -> dict:
    """Output path -> renderer, for `gen_tokens.run` to merge with its own."""
    built = build(patterns)
    return {
        VECTORS_OUTPUT: lambda sources: render_json(built),
        TS_OUTPUT: lambda sources: render_ts(built),
        RS_OUTPUT: lambda sources: render_rs(built),
    }
