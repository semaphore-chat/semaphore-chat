#!/usr/bin/env python3
"""Validate the shared Lucide icon set and render it for both clients.

`design/icons/icons.json` names the pinned upstream release (`lucide`) and maps
each icon name to the file it comes from in `design/icons/lucide/`. This module
checks that set and renders it: the web client's node map
(`frontend/src/kit/icons/generated.ts`), the Rust client's enum and asset
accessors (`native/crates/semaphore-design/src/lounge_icons.rs`) and one asset
per icon (`native/crates/semaphore-design/assets/lucide/<file>.svg`).

The assets are rebuilt from the validated shapes: the licence line, then a
canonical `<svg>` element drawing those shapes in `#000`, because GPUI draws an
SVG as an alpha mask. The node maps carry only the shape elements, typed for
the web and named for Rust. Nothing the validator has not seen can reach
either client.

`design/gen/gen_tokens.py` renders these outputs; run that program, not this
one. Only the Python standard library is used.
"""

from __future__ import annotations

import json
import re
import xml.etree.ElementTree as ElementTree
from pathlib import Path
from typing import Callable, NoReturn
from xml.sax.saxutils import escape

from gen_error import TokenError

# Relative to the repo root, so `load_icons` and the renderers read the same way
# below any checkout.
SOURCE = Path("design") / "icons"
TS_OUTPUT = Path("frontend/src/kit/icons/generated.ts")
RS_OUTPUT = Path("native/crates/semaphore-design/src/lounge_icons.rs")
ASSET_ROOT = Path("native/crates/semaphore-design/assets/lucide")

HEADER = (
    "// @generated by design/gen/gen_tokens.py from design/icons/icons.json.\n"
    "// Do not edit by hand: change the source or the generator and re-run it."
)
TS_LICENCE = (
    "/*! Icons: Lucide v{version}, ISC licence (parts MIT, from Feather). "
    "See design/icons/LICENSE. */"
)

# A kit name is PascalCase (`UserPlus`); the file is Lucide's kebab-case name
# (`user-plus`), without `.svg`.
NAME = re.compile(r"[A-Z][A-Za-z0-9]*")
FILE = re.compile(r"[a-z0-9]+(-[a-z0-9]+)*")
VERSION = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+")

SVG_NAMESPACE = "http://www.w3.org/2000/svg"
SVG_TAG = f"{{{SVG_NAMESPACE}}}svg"
# The one line every source file starts with; the version is `icons.json`'s.
LICENCE = "<!-- @license lucide-static v{version} - ISC -->"

# The only elements a Lucide icon may contain, and the only attributes they
# carry. Anything else (`<script>`, `<style>`, `href`, `on*`, a fill, a
# transform) is an error: these files are drawn, never interpreted.
SHAPES = ("path", "circle", "rect", "line", "polyline", "polygon", "ellipse")
# Full tags, namespace included: a child in any other namespace is a different
# element, whatever its local name says.
SHAPE_TAGS = {f"{{{SVG_NAMESPACE}}}{shape}": shape for shape in SHAPES}
CHILD_ATTRIBUTES = frozenset(
    "d cx cy r rx ry x y x1 y1 x2 y2 width height points".split()
)
# The values those attributes may hold, matched in full: path data letters and
# numbers, a point list, and one number, so nothing else (`javascript:…`,
# `1e3x`) can slip into an attribute the renderers copy.
PATH_DATA = re.compile(r"[MmLlHhVvCcSsQqTtAaZz0-9.,\s+-]+")
POINT_LIST = re.compile(r"[0-9.,\s-]+")
NUMBER = re.compile(r"-?[0-9]*\.?[0-9]+")
# The root may also carry the licence-compatible extras the real files have:
# `xmlns` and `class`, whose tokens must all be Lucide's own.
ROOT_ATTRIBUTES = frozenset(
    "xmlns class width height viewBox fill stroke "
    "stroke-width stroke-linecap stroke-linejoin".split()
)
ROOT_VALUES = {
    "width": "24",
    "height": "24",
    "viewBox": "0 0 24 24",
    "fill": "none",
    "stroke": "currentColor",
    "stroke-width": "2",
    "stroke-linecap": "round",
    "stroke-linejoin": "round",
}


def _fail(path: str, message: str) -> NoReturn:
    raise TokenError(f"{path}: {message}")


def _read_json(path: Path) -> object:
    """Parse `icons.json`; a repeated key is an error, as it would silently vanish."""

    def no_repeats(pairs: list[tuple[str, object]]) -> dict:
        result: dict = {}
        for key, value in pairs:
            if key in result:
                _fail(f"icons.{key}", "repeated key")
            result[key] = value
        return result

    try:
        return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=no_repeats)
    except json.JSONDecodeError as error:
        _fail("icons.json", f"not valid JSON: {error}")


def _check_attributes(
    where: str, tag: str, attributes: dict, allowed: frozenset[str]
) -> None:
    """Reject namespaced or unknown attributes on `tag`."""
    for name in attributes:
        if name.startswith("{"):
            _fail(where, f"<{tag}> has the namespaced attribute {name!r}")
        if name not in allowed:
            _fail(where, f"<{tag}> attribute '{name}' is not allowed")


def _validate_root(where: str, root: ElementTree.Element, file: str) -> None:
    _check_attributes(where, "svg", root.attrib, ROOT_ATTRIBUTES)
    for name, expected in ROOT_VALUES.items():
        if name not in root.attrib:
            _fail(where, f'root is missing {name}="{expected}"')
        if root.attrib[name] != expected:
            _fail(where, f"root {name} is {root.attrib[name]!r}, expected {expected!r}")
    if "class" in root.attrib:
        allowed = {"lucide", f"lucide-{file}"}
        tokens = root.attrib["class"].split()
        if not tokens or any(token not in allowed for token in tokens):
            _fail(
                where,
                f'class {root.attrib["class"]!r} must be "lucide" or "lucide-{file}" '
                "tokens only",
            )
    if (root.text or "").strip():
        _fail(where, "unexpected text inside <svg>")


def _validate_child(where: str, child: ElementTree.Element) -> tuple[str, dict[str, str]]:
    tag = SHAPE_TAGS.get(child.tag)
    if tag is None:
        _fail(
            where,
            f"child tag {child.tag!r} is not one of {', '.join(SHAPES)} "
            f"in {SVG_NAMESPACE}",
        )
    _check_attributes(where, tag, child.attrib, CHILD_ATTRIBUTES)
    for name, value in child.attrib.items():
        pattern = PATH_DATA if name == "d" else POINT_LIST if name == "points" else NUMBER
        if not pattern.fullmatch(value):
            _fail(where, f"<{tag}> {name}={value!r} does not match {pattern.pattern}")
    if len(child):
        _fail(where, f"<{tag}> must not contain elements")
    if (child.text or "").strip() or (child.tail or "").strip():
        _fail(where, f"<{tag}> carries text")
    return tag, dict(child.attrib)


def _validate_svg(path: Path, file: str, version: str) -> list:
    """Check the raw text of one upstream SVG, then its tree, and return its shapes."""
    where = f"icons/{file}.svg"
    try:
        svg = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        _fail(where, "expected UTF-8")
    # Check the text before ElementTree sees it: parsing drops comments and
    # processing instructions and expands entities, so the tree alone cannot
    # prove what the file holds.
    licence = LICENCE.format(version=version) + "\n"
    if not svg.startswith(licence):
        _fail(where, f"expected the licence line {licence.rstrip()!r} first")
    markup = svg[len(licence) :]
    for needle, rule in (
        ("<!", "comments, DOCTYPEs and CDATA sections"),
        ("<?", "processing instructions"),
        ("&", "entities and character references"),
    ):
        if needle in markup:
            _fail(where, f"{rule} are not allowed (found {needle!r})")
    if not markup.startswith("<svg"):
        _fail(where, "expected the <svg> element straight after the licence line")
    try:
        root = ElementTree.fromstring(markup)
    except ElementTree.ParseError as error:
        _fail(where, f"not well-formed XML: {error}")
    if root.tag != SVG_TAG:
        _fail(where, f"the root element is {root.tag!r}, expected {SVG_TAG!r}")
    _validate_root(where, root, file)
    return [_validate_child(where, child) for child in root]


def _reject_extra_files(directory: Path, files: set[str]) -> None:
    """Every file in `lucide/` must be named by `icons.json`."""
    expected = {f"{file}.svg" for file in files}
    for path in sorted(directory.iterdir()):
        if path.is_file() and path.name not in expected:
            _fail(f"icons/{path.name}", "no name in design/icons/icons.json")


def load_icons(root: Path) -> dict:
    """Load and validate the icon sources below `root`, in `icons.json` order.

    Raises `TokenError` with a message starting `icons.<Name>` or
    `icons/<file>.svg`. Each icon keeps the shape elements its file draws, not
    the file itself: the native asset is rebuilt from these.
    """
    directory = Path(root) / SOURCE
    document = _read_json(directory / "icons.json")
    if not isinstance(document, dict) or set(document) != {"lucide", "icons"}:
        _fail("icons", "expected an object with exactly 'lucide' and 'icons'")
    version = document["lucide"]
    if not isinstance(version, str) or not VERSION.fullmatch(version):
        _fail("icons.lucide", f"expected a version like 1.71.0, got {version!r}")
    entries = document["icons"]
    if not isinstance(entries, dict):
        _fail("icons", f"expected an object naming each icon's file, got {entries!r}")
    names_by_file: dict[str, str] = {}
    icons: list[dict] = []
    for name, file in entries.items():
        if not isinstance(name, str) or not NAME.fullmatch(name):
            _fail(f"icons.{name}", f"expected a PascalCase name, got {name!r}")
        if not isinstance(file, str) or not FILE.fullmatch(file):
            _fail(f"icons.{name}", f"expected a kebab-case file name, got {file!r}")
        if file in names_by_file:
            _fail(f"icons.{name}", f"file '{file}' is already used by '{names_by_file[file]}'")
        names_by_file[file] = name
        path = directory / "lucide" / f"{file}.svg"
        if not path.is_file():
            _fail(f"icons/{file}.svg", "no such file in design/icons/lucide")
        nodes = _validate_svg(path, file, version)
        icons.append({"name": name, "file": file, "nodes": nodes})
    _reject_extra_files(directory / "lucide", set(names_by_file))
    return {"version": version, "icons": icons}


def _string(value: str) -> str:
    """A single-quoted TypeScript string literal."""
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _ts_node(tag: str, attributes: dict[str, str]) -> str:
    pairs = ", ".join(f"{name}: {_string(value)}" for name, value in attributes.items())
    return f"['{tag}', {{ {pairs} }}]" if pairs else f"['{tag}', {{}}]"


def render_icons_ts(icons: dict) -> str:
    """Render the web client's node map, its `IconName` type and its name list."""
    lines = [
        HEADER,
        TS_LICENCE.format(version=icons["version"]),
        "",
        "export const iconNodes = {",
    ]
    for icon in icons["icons"]:
        shapes = ", ".join(_ts_node(tag, attributes) for tag, attributes in icon["nodes"])
        lines.append(f"  {icon['name']}: [{shapes}],")
    lines.extend(
        [
            "} as const;",
            "",
            "export type IconName = keyof typeof iconNodes;",
            "",
            "export const iconNames = [",
        ]
    )
    lines.extend(f"  {_string(icon['name'])}," for icon in icons["icons"])
    lines.append("] as const;")
    return "\n".join(lines) + "\n"


def render_icons_rs(icons: dict) -> str:
    """Render the Rust client's enum, its `ALL` list and its three lookups."""
    names = [icon["name"] for icon in icons["icons"]]
    lines = [
        HEADER,
        "",
        "//! The shared Lucide icon set, generated for the Rust client.",
        "//!",
        "//! Every `svg` is the icon's validated shapes rebuilt as one canonical SVG",
        "//! drawing them in `#000`, because GPUI draws an SVG as an alpha mask.",
        "",
        "/// One icon of the set shared by both clients.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]",
        "pub enum LoungeIcon {",
    ]
    lines.extend(f"    {name}," for name in names)
    lines.extend(["}", "", "impl LoungeIcon {"])
    lines.append("    /// Every icon, in `design/icons/icons.json` order.")
    lines.append(f"    pub const ALL: [LoungeIcon; {len(names)}] = [")
    lines.extend(f"        LoungeIcon::{name}," for name in names)
    lines.append("    ];")
    lines.extend(
        [
            "",
            "    /// The icon's name in `design/icons/icons.json` (`Mic`).",
            "    pub fn name(self) -> &'static str {",
            "        match self {",
        ]
    )
    lines.extend(f'            Self::{name} => "{name}",' for name in names)
    lines.extend(["        }", "    }", ""])
    lines.append('    /// The asset\'s path below `assets/` (`lucide/mic.svg`).')
    lines.extend(["    pub fn asset_path(self) -> &'static str {", "        match self {"])
    lines.extend(
        f'            Self::{icon["name"]} => "lucide/{icon["file"]}.svg",'
        for icon in icons["icons"]
    )
    lines.extend(["        }", "    }", ""])
    lines.append("    /// The asset's bytes: the validated shapes drawn in `#000`.")
    lines.extend(["    pub fn svg(self) -> &'static [u8] {", "        match self {"])
    lines.extend(
        f'            Self::{icon["name"]} => '
        f'include_bytes!("../assets/lucide/{icon["file"]}.svg"),'
        for icon in icons["icons"]
    )
    lines.extend(["        }", "    }", "}"])
    return "\n".join(lines) + "\n"


# The element every native asset carries, with the shapes drawn in the mask
# colour. Built here rather than copied from the source, so the native client
# only ever draws what the validator accepted.
NATIVE_SVG_OPEN = (
    f'<svg xmlns="{SVG_NAMESPACE}" width="24" height="24" viewBox="0 0 24 24" '
    'fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" '
    'stroke-linejoin="round">'
)
# Attribute values are copied from the source, so escape them for the quotes.
QUOTE = {'"': "&quot;"}


def render_native_svg(icon: dict, version: str) -> str:
    """The icon's native asset: the shapes its source was validated to draw."""
    lines = [LICENCE.format(version=version), NATIVE_SVG_OPEN]
    for tag, attributes in icon["nodes"]:
        pairs = " ".join(
            f'{name}="{escape(value, QUOTE)}"' for name, value in attributes.items()
        )
        lines.append(f"  <{tag} {pairs} />" if pairs else f"  <{tag} />")
    lines.append("</svg>")
    return "\n".join(lines) + "\n"


def _native_renderer(icon: dict, version: str) -> Callable[[dict], str]:
    def render(_sources: dict) -> str:
        return render_native_svg(icon, version)

    return render


def renderers(icons: dict) -> dict[Path, Callable[[dict], str]]:
    """Every icon output, keyed by its path below the repo root.

    The two maps take the loaded sources like the other renderers. Each asset is
    its own output, so an icon removed from the set is reported stale (and
    deleted on a normal run) instead of lingering.
    """
    outputs: dict[Path, Callable[[dict], str]] = {
        TS_OUTPUT: lambda sources: render_icons_ts(sources["icons"]),
        RS_OUTPUT: lambda sources: render_icons_rs(sources["icons"]),
    }
    for icon in icons["icons"]:
        outputs[ASSET_ROOT / f"{icon['file']}.svg"] = _native_renderer(icon, icons["version"])
    return outputs
